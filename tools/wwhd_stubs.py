#!/usr/bin/env python3
"""Write runtime/src/wwhd_unlinked.cpp: a stub for every Wind Waker HD game function the inherited
WWHD runtime still names (f_/hook_/site_XXXXXXXX) that does not exist in the BotW recompilation.

usage: wwhd_stubs.py BUILD_LOG   (the log of a failed link: "Undefined symbols ... "_f_0200E240_orig")

These come from WWHD-only features (interpolation, true 60, turbo, ...) whose hooks are never
registered for BotW, so the stubs should never run; if one does, it stops the game by name instead of
running Wind Waker logic on BotW memory. Remove entries as those features are deleted or ported.
"""
import re
import sys

syms = sorted(set(re.findall(r'^\s+"_((?:f|hook|site)_[0-9A-F]{8}(?:_orig)?)"', open(sys.argv[1]).read(), re.M)))
out = ["// Generated by tools/wwhd_stubs.py; see that script.",
       '#include "runtime.h"', '#include "ppc.h"', "", 'extern "C" {']
for s in syms:
    out.append('void %s(Cpu*) { fatal("WWHD-only game function %s called (no BotW equivalent)"); }' % (s, s))
out += ["}", ""]
open("runtime/src/wwhd_unlinked.cpp", "w").write("\n".join(out))
print("%d stubs" % len(syms))
